"""Render contracts/CONTRACT_FIELDS.md from the validator specs, so the field reference never drifts.

    python3 -m contracts.tools.render_fields
"""
import os
import sys

from ..taxonomy import TAXONOMY_DOC, _ENTRY
from ..validate import (EVALUATION_RECORD, IMAGE_MANIFEST, IMAGE_PROFILE, INFERENCE_OUTPUT, MODEL_CARD,
                        POETRY_RECORD, RECOMMENDATIONS, RETRIEVAL_QUERY)

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "CONTRACT_FIELDS.md")
SECTIONS = [
    ("taxonomy", "contracts/taxonomy/taxonomy_v1.json (JSON)", TAXONOMY_DOC),
    ("taxonomy label entry", "items of `labels`", _ENTRY),
    ("image_manifest", "JSONL, one record per image", IMAGE_MANIFEST),
    ("model_card", "JSON", MODEL_CARD),
    ("inference_output", "JSON, one per analysed image", INFERENCE_OUTPUT),
    ("image_profile", "JSON, one per confirmed user choice", IMAGE_PROFILE),
    ("poetry_record", "JSONL, one record per verse", POETRY_RECORD),
    ("retrieval_query", "JSON", RETRIEVAL_QUERY),
    ("recommendations", "JSON", RECOMMENDATIONS),
    ("evaluation_record", "JSONL, one record per judgment", EVALUATION_RECORD),
]


def describe(spec):
    parts = [spec.kind]
    if spec.kind == "id" and spec.layers:
        parts.append("layer " + " / ".join(spec.layers))
    if spec.enum:
        parts.append("one of " + " / ".join(sorted(spec.enum)))
    if spec.fmt:
        parts.append("format " + spec.fmt)
    if spec.min is not None:
        parts.append(("> " if spec.exclusive_min else ">= ") + str(spec.min))
    if spec.max is not None:
        parts.append("<= " + str(spec.max))
    if spec.min_items is not None:
        parts.append(f"at least {spec.min_items} item(s)")
    if spec.max_items is not None:
        parts.append(f"at most {spec.max_items} item(s)")
    if spec.max_words is not None:
        parts.append(f"at most {spec.max_words} words")
    if spec.allow_empty:
        parts.append("may be empty")
    if spec.kind == "list" and spec.items is not None and spec.items.kind != "obj":
        parts.append("items: " + describe(spec.items))
    if spec.kind == "map":
        if spec.keys is not None:
            parts.append("keys: " + describe(spec.keys))
        if spec.values is not None and spec.values.kind != "obj":
            parts.append("values: " + describe(spec.values))
    return ", ".join(parts)


def walk(fields, prefix, rows):
    for name, spec in fields.items():
        path = f"{prefix}.{name}" if prefix else name
        rows.append((path, describe(spec), "R" if spec.required else "O", "yes" if spec.nullable else ""))
        if spec.kind == "obj" and spec.fields:
            walk(spec.fields, path, rows)
        elif spec.kind == "list" and spec.items is not None and spec.items.kind == "obj":
            walk(spec.items.fields, path + "[]", rows)
        elif spec.kind == "map" and spec.values is not None and spec.values.kind == "obj":
            walk(spec.values.fields, path + ".<key>", rows)


def render():
    lines = ["# Contract field reference (generated)", "",
             "Generated by `python3 -m contracts.tools.render_fields` from the specs in `contracts/validate.py` and "
             "`contracts/taxonomy.py`. Do not edit by hand. Cross-field rules are in `contracts/CONTRACTS.md`.", "",
             "R = required, O = optional. Unknown fields are rejected (E_UNKNOWN_FIELD).", ""]
    for title, fmt, fields in SECTIONS:
        rows = []
        walk(fields, "", rows)
        lines += [f"## {title}", "", f"Format: {fmt}", "", "| Field | Type and constraints | R/O | Null |",
                  "|---|---|---|---|"]
        lines += [f"| `{path}` | {kind} | {req} | {null} |" for path, kind, req, null in rows]
        lines.append("")
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
